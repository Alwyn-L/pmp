-- =============================================================================
-- V1 RBAC 核心表（app schema）
-- 说明：公共字段 id/created_at/updated_at/deleted 统一；软删除 deleted=1
-- =============================================================================

CREATE TABLE IF NOT EXISTS app.sys_user (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR(64) NOT NULL UNIQUE,
  password_hash VARCHAR(100) NOT NULL,
  nickname VARCHAR(64),
  dept_id BIGINT,
  phone VARCHAR(32),
  email VARCHAR(128),
  status VARCHAR(16) NOT NULL DEFAULT '启用',
  fail_count INT NOT NULL DEFAULT 0,
  locked_until TIMESTAMPTZ,
  last_login_at TIMESTAMPTZ,
  last_login_ip VARCHAR(64),
  created_by VARCHAR(64),
  created_at TIMESTAMPTZ DEFAULT now(),
  updated_by VARCHAR(64),
  updated_at TIMESTAMPTZ DEFAULT now(),
  deleted SMALLINT NOT NULL DEFAULT 0,
  version INT NOT NULL DEFAULT 0
);
COMMENT ON TABLE app.sys_user IS '平台账号';

CREATE TABLE IF NOT EXISTS app.sys_role (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(64) NOT NULL UNIQUE,
  name VARCHAR(64) NOT NULL,
  data_scope VARCHAR(24) NOT NULL DEFAULT 'DEPT',
  status VARCHAR(16) NOT NULL DEFAULT '启用',
  remark VARCHAR(255),
  created_by VARCHAR(64),
  created_at TIMESTAMPTZ DEFAULT now(),
  updated_by VARCHAR(64),
  updated_at TIMESTAMPTZ DEFAULT now(),
  deleted SMALLINT NOT NULL DEFAULT 0,
  version INT NOT NULL DEFAULT 0
);
COMMENT ON TABLE app.sys_role IS '角色，code/name 全局唯一';

CREATE TABLE IF NOT EXISTS app.sys_menu (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  parent_id BIGINT NOT NULL DEFAULT 0,
  name VARCHAR(64) NOT NULL,
  type VARCHAR(16) NOT NULL DEFAULT 'MENU',
  path VARCHAR(255),
  component VARCHAR(255),
  icon VARCHAR(64),
  perm_code VARCHAR(128),
  sort INT NOT NULL DEFAULT 0,
  visible SMALLINT NOT NULL DEFAULT 1,
  external SMALLINT NOT NULL DEFAULT 0,
  status VARCHAR(16) NOT NULL DEFAULT '启用',
  created_by VARCHAR(64),
  created_at TIMESTAMPTZ DEFAULT now(),
  updated_by VARCHAR(64),
  updated_at TIMESTAMPTZ DEFAULT now(),
  deleted SMALLINT NOT NULL DEFAULT 0,
  version INT NOT NULL DEFAULT 0
);
COMMENT ON TABLE app.sys_menu IS '菜单/按钮目录树，type=DIR/MENU/BUTTON/LINK';

CREATE TABLE IF NOT EXISTS app.sys_dept (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  parent_id BIGINT NOT NULL DEFAULT 0,
  ancestors VARCHAR(255) NOT NULL DEFAULT '0',
  name VARCHAR(64) NOT NULL,
  sort INT NOT NULL DEFAULT 0,
  status VARCHAR(16) NOT NULL DEFAULT '启用',
  created_by VARCHAR(64),
  created_at TIMESTAMPTZ DEFAULT now(),
  updated_by VARCHAR(64),
  updated_at TIMESTAMPTZ DEFAULT now(),
  deleted SMALLINT NOT NULL DEFAULT 0,
  version INT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS app.sys_user_role (
  user_id BIGINT NOT NULL,
  role_id BIGINT NOT NULL,
  PRIMARY KEY (user_id, role_id)
);
CREATE TABLE IF NOT EXISTS app.sys_role_menu (
  role_id BIGINT NOT NULL,
  menu_id BIGINT NOT NULL,
  PRIMARY KEY (role_id, menu_id)
);
CREATE TABLE IF NOT EXISTS app.sys_role_dept (
  role_id BIGINT NOT NULL,
  dept_id BIGINT NOT NULL,
  PRIMARY KEY (role_id, dept_id)
);

CREATE TABLE IF NOT EXISTS app.sys_login_log (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR(64),
  ip VARCHAR(64),
  ua VARCHAR(255),
  result VARCHAR(16),
  msg VARCHAR(255),
  created_at TIMESTAMPTZ DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_login_log_time ON app.sys_login_log(created_at DESC);

CREATE TABLE IF NOT EXISTS app.sys_oper_log (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT,
  username VARCHAR(64),
  module VARCHAR(64),
  action VARCHAR(32),
  uri VARCHAR(255),
  params TEXT,
  ip VARCHAR(64),
  cost_ms INT,
  result VARCHAR(16),
  trace_id VARCHAR(64),
  created_at TIMESTAMPTZ DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_oper_log_time ON app.sys_oper_log(created_at DESC);

CREATE TABLE IF NOT EXISTS app.sys_dict_type (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(64) NOT NULL UNIQUE,
  name VARCHAR(64) NOT NULL,
  status VARCHAR(16) NOT NULL DEFAULT '启用',
  created_at TIMESTAMPTZ DEFAULT now(),
  deleted SMALLINT NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS app.sys_dict_item (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  type_code VARCHAR(64) NOT NULL,
  label VARCHAR(64) NOT NULL,
  value VARCHAR(64) NOT NULL,
  sort INT NOT NULL DEFAULT 0,
  status VARCHAR(16) NOT NULL DEFAULT '启用',
  created_at TIMESTAMPTZ DEFAULT now(),
  deleted SMALLINT NOT NULL DEFAULT 0,
  UNIQUE (type_code, value)
);

CREATE TABLE IF NOT EXISTS app.sys_page_resource (
  page_id VARCHAR(64) PRIMARY KEY,
  table_name VARCHAR(64) NOT NULL,
  module VARCHAR(64),
  title VARCHAR(128),
  api_prefix VARCHAR(128) NOT NULL,
  perm_prefix VARCHAR(128) NOT NULL,
  created_at TIMESTAMPTZ DEFAULT now()
);
